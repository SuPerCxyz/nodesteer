func nullableFloat(value *float64) any {
	if value == nil {
		return nil
	}
	return *value
}

func boolInt(value bool) int {
	if value {
		return 1
	}
	return 0
}

func notificationWhere(filter AlertNotificationFilter) (string, []any) {
	conditions := []string{}
	args := []any{}
	if filter.EventID != "" {
		conditions = append(conditions, `event_id = ?`)
		args = append(args, filter.EventID)
	}
	if filter.ChannelID != "" {
		conditions = append(conditions, `channel_id = ?`)
		args = append(args, filter.ChannelID)
	}
	if filter.Status != "" {
		conditions = append(conditions, `status = ?`)
		args = append(args, filter.Status)
	}
	if len(conditions) == 0 {
		return "", args
	}
	return " WHERE " + strings.Join(conditions, " AND "), args
}

func alertEventWhere(filter AlertEventFilter) (string, []any) {
	conditions := []string{}
	args := []any{}
	switch filter.State {
	case "active":
		conditions = append(conditions, `status IN ('pending', 'firing', 'silenced')`)
	case "history":
		conditions = append(conditions, `status = 'resolved'`)
	}
	if filter.Status != "" {
		conditions = append(conditions, `status = ?`)
		args = append(args, filter.Status)
	}
	if filter.RuleID != "" {
		conditions = append(conditions, `rule_id = ?`)
		args = append(args, filter.RuleID)
	}
	if filter.NodeID != "" {
		conditions = append(conditions, `node_id = ?`)
		args = append(args, filter.NodeID)
	}
	if filter.Severity != "" {
		conditions = append(conditions, `severity = ?`)
		args = append(args, filter.Severity)
	}
	if !filter.Since.IsZero() {
		conditions = append(conditions, `updated_at >= ?`)
		args = append(args, formatAlertTime(filter.Since))
	}
	if !filter.Until.IsZero() {
		conditions = append(conditions, `updated_at <= ?`)
		args = append(args, formatAlertTime(filter.Until))
	}
	if len(conditions) == 0 {
		return "", args
	}
	return " WHERE " + strings.Join(conditions, " AND "), args
}
