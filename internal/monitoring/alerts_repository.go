func (r *AlertRepository) MarkNotificationSent(ctx context.Context, id string, attempts int, now time.Time) error {
	tx, err := r.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	stamp := formatAlertTime(now)
	result, err := tx.ExecContext(ctx, `UPDATE alert_notifications SET
		status = 'sent', attempts = ?, last_error = '', sent_at = ?, next_attempt_at = '', updated_at = ?
		WHERE id = ?`, attempts, stamp, stamp, id)
	if err != nil {
		return err
	}
	affected, err := result.RowsAffected()
	if err != nil {
		return err
	}
	if affected == 0 {
		return sql.ErrNoRows
	}
	if err := insertNotificationAttemptTx(ctx, tx, id, attempts, "sent", "", now); err != nil {
		return err
	}
	return tx.Commit()
}

func (r *AlertRepository) RecordNotificationAttempt(ctx context.Context, id string, attempt int, status, message string, final bool, next, now time.Time) error {
	status = strings.TrimSpace(status)
	if status != "sent" && status != "failed" {
		return errors.New("invalid notification attempt status")
	}
	tx, err := r.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	notificationStatus := "pending"
	nextValue := formatAlertTime(next)
	if final {
		notificationStatus = "failed"
		nextValue = ""
	}
	stamp := formatAlertTime(now)
	result, err := tx.ExecContext(ctx, `UPDATE alert_notifications SET
		status = ?, attempts = ?, last_error = ?, next_attempt_at = ?, updated_at = ?
		WHERE id = ?`, notificationStatus, attempt, message, nextValue, stamp, id)
	if err != nil {
		return err
	}
	affected, err := result.RowsAffected()
	if err != nil {
		return err
	}
	if affected == 0 {
		return sql.ErrNoRows
	}
	if err := insertNotificationAttemptTx(ctx, tx, id, attempt, status, message, now); err != nil {
		return err
	}
	return tx.Commit()
}

func insertNotificationAttemptTx(ctx context.Context, tx *sql.Tx, notificationID string, attempt int, status, message string, now time.Time) error {
	_, err := tx.ExecContext(ctx, `INSERT INTO alert_notification_attempts
		(notification_id, attempt, status, error, attempted_at) VALUES (?, ?, ?, ?, ?)`,
		notificationID, attempt, status, message, formatAlertTime(now))
	return err
}

// ListNotifications 分页查询发件箱记录，并为每条记录附加尝试明细。
// 错误文本在返回前再次归一化，避免历史数据或外部输入把 URL/token 带到 API。
func (r *AlertRepository) ListNotifications(ctx context.Context, filter AlertNotificationFilter) ([]AlertNotificationRecord, int, error) {
	where, args := notificationWhere(filter)
	var total int
	if err := r.db.QueryRowContext(ctx, `SELECT COUNT(*) FROM alert_notifications`+where, args...).Scan(&total); err != nil {
		return nil, 0, err
	}
	limit := filter.Limit
	if limit <= 0 {
		limit = 50
	}
	if limit > 200 {
		limit = 200
	}
	offset := filter.Offset
	if offset < 0 {
		offset = 0
	}
	queryArgs := append(append([]any{}, args...), limit, offset)
	rows, err := r.db.QueryContext(ctx, `SELECT `+notificationColumns+` FROM alert_notifications`+where+
		` ORDER BY created_at DESC, id DESC LIMIT ? OFFSET ?`, queryArgs...)
	if err != nil {
		return nil, 0, err
	}
	defer rows.Close()
	records := []AlertNotificationRecord{}
	ids := []string{}
	for rows.Next() {
		notification, err := scanNotification(rows)
		if err != nil {
			return nil, 0, err
		}
		notification.LastError = sanitizeNotificationRecordError(notification.LastError)
		records = append(records, AlertNotificationRecord{
			AlertNotification: notification,
			AttemptDetails:    []AlertNotificationAttempt{},
		})
		ids = append(ids, notification.ID)
	}
	if err := rows.Err(); err != nil {
		return nil, 0, err
	}
	_ = rows.Close()
	if len(ids) == 0 {
		return records, total, nil
	}
	placeholders := strings.TrimRight(strings.Repeat("?,", len(ids)), ",")
	attemptArgs := make([]any, 0, len(ids))
	for _, id := range ids {
		attemptArgs = append(attemptArgs, id)
	}
	attemptRows, err := r.db.QueryContext(ctx, `SELECT notification_id, attempt, status, error, attempted_at
		FROM alert_notification_attempts WHERE notification_id IN (`+placeholders+`)
		ORDER BY notification_id, attempt`, attemptArgs...)
	if err != nil {
		return nil, 0, err
	}
	defer attemptRows.Close()
	attempts := map[string][]AlertNotificationAttempt{}
	for attemptRows.Next() {
		var notificationID string
		var attempt AlertNotificationAttempt
		var attemptedAt string
		if err := attemptRows.Scan(&notificationID, &attempt.Attempt, &attempt.Status, &attempt.Error, &attemptedAt); err != nil {
			return nil, 0, err
		}
		if attempt.AttemptedAt, err = parseAlertTime(attemptedAt); err != nil {
			return nil, 0, err
		}
		attempt.Error = sanitizeNotificationRecordError(attempt.Error)
		attempts[notificationID] = append(attempts[notificationID], attempt)
	}
	if err := attemptRows.Err(); err != nil {
		return nil, 0, err
	}
	for index := range records {
		if details, ok := attempts[records[index].ID]; ok {
			records[index].AttemptDetails = details
		}
	}
	return records, total, nil
}

func sanitizeNotificationRecordError(message string) string {
	message = strings.TrimSpace(message)
	if message == "" {
		return ""
	}
	return normalizeNotificationError(errors.New(message))
}

