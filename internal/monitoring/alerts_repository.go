func (r *AlertRepository) AckAlertEvent(ctx context.Context, id, userID, username string, now time.Time) error {
	now = now.UTC()
	tx, err := r.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	result, err := tx.ExecContext(ctx, `UPDATE alert_events SET
		acknowledged_at = CASE WHEN acknowledged_at = '' THEN ? ELSE acknowledged_at END,
		acknowledged_by = CASE WHEN acknowledged_by = '' THEN ? ELSE acknowledged_by END,
		updated_at = ?
		WHERE id = ? AND status IN ('pending', 'firing', 'silenced')`,
		formatAlertTime(now), username, formatAlertTime(now), id)
	if err != nil {
		return err
	}
	affected, err := result.RowsAffected()
	if err != nil {
		return err
	}
	if affected == 0 {
		var status string
		err := tx.QueryRowContext(ctx, `SELECT status FROM alert_events WHERE id = ?`, id).Scan(&status)
		if errors.Is(err, sql.ErrNoRows) {
			return sql.ErrNoRows
		}
		if err != nil {
			return err
		}
		return fmt.Errorf("%w: alert event is not active", ErrAlertConflict)
	}
	if err := writeAuditDetail(ctx, tx, "alert_event", "ack", id, "by="+username); err != nil {
		return err
	}
	return tx.Commit()
}

