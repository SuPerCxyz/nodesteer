func channelReferencedTx(ctx context.Context, tx *sql.Tx, channelID string) (bool, error) {
	rows, err := tx.QueryContext(ctx, `SELECT channels_json FROM alert_rules`)
	if err != nil {
		return false, err
	}
	defer rows.Close()
	for rows.Next() {
		var raw string
		if err := rows.Scan(&raw); err != nil {
			return false, err
		}
		var ids []string
		if err := json.Unmarshal([]byte(raw), &ids); err != nil {
			return false, err
		}
		for _, id := range ids {
			if id == channelID {
				return true, nil
			}
		}
	}
	return false, rows.Err()
}

func ruleRuntimeChanged(old, next AlertRule) bool {
	return old.NodeID != next.NodeID ||
		old.Metric != next.Metric ||
		old.Series != next.Series ||
		old.Operator != next.Operator ||
		old.Threshold != next.Threshold ||
		old.DurationSec != next.DurationSec ||
		old.RecoverySec != next.RecoverySec ||
		old.CooldownSec != next.CooldownSec
}

func resetAlertRuntimeTx(ctx context.Context, tx *sql.Tx, ruleID, message string, now time.Time) error {
	stamp := formatAlertTime(now)
	// 规则被禁用/删除/重配后，尚未发送的旧通知不再有意义。
	if _, err := tx.ExecContext(ctx, `UPDATE alert_notifications SET status = 'failed', last_error = ?, next_attempt_at = '', updated_at = ?
		WHERE status = 'pending' AND event_id IN (SELECT id FROM alert_events WHERE rule_id = ?)`,
		message, stamp, ruleID); err != nil {
		return err
	}
	if _, err := tx.ExecContext(ctx, `UPDATE alert_events SET status = 'resolved', resolved_at = ?, message = ?, updated_at = ?
		WHERE rule_id = ? AND status IN ('pending', 'firing', 'silenced')`,
		stamp, message, stamp, ruleID); err != nil {
		return err
	}
	_, err := tx.ExecContext(ctx, `DELETE FROM alert_states WHERE rule_id = ?`, ruleID)
	return err
}

