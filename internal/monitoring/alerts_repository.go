// ApplyDecision 在一个事务内更新状态、事件与通知发件箱。
// 若规则在评估后被修改或禁用，则静默丢弃本次决策，避免覆盖新配置。
func (r *AlertRepository) ApplyDecision(ctx context.Context, rule AlertRule, decision AlertDecision) error {
	tx, err := r.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()

	var enabled int
	var updatedAt string
	if err := tx.QueryRowContext(ctx, `SELECT enabled, updated_at FROM alert_rules WHERE id = ?`, rule.ID).
		Scan(&enabled, &updatedAt); err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return nil
		}
		return err
	}
	if enabled == 0 || updatedAt != formatAlertTime(rule.UpdatedAt) {
		return nil
	}

	now := decision.State.LastEvaluatedAt.UTC()
	if now.IsZero() {
		now = time.Now().UTC()
	}
	event := decision.Event
	if event != nil {
		if event.CreatedAt.IsZero() {
			event.CreatedAt = now
		}
		if event.StartedAt.IsZero() {
			event.StartedAt = now
		}
		if event.UpdatedAt.IsZero() {
			event.UpdatedAt = now
		}
		if event.ID == "" {
			event.ID = uuid.NewString()
			if err := insertAlertEventTx(ctx, tx, *event); err != nil {
				return err
			}
		} else if err := updateAlertEventTx(ctx, tx, *event); err != nil {
			return err
		}
		if event.Status == AlertStatusPending || event.Status == AlertStatusFiring || event.Status == AlertStatusSilenced {
			decision.State.EventID = event.ID
		} else {
			decision.State.EventID = ""
		}
	}
	if decision.State.UpdatedAt.IsZero() {
		decision.State.UpdatedAt = now
	}
	if err := upsertAlertStateTx(ctx, tx, decision.State); err != nil {
		return err
	}

	if decision.Notify && event != nil && len(rule.Channels) > 0 {
		inserted := 0
		for _, channelID := range rule.Channels {
			var channelType string
			var channelEnabled int
			err := tx.QueryRowContext(ctx, `SELECT type, enabled FROM notification_channels WHERE id = ?`, channelID).
				Scan(&channelType, &channelEnabled)
			if errors.Is(err, sql.ErrNoRows) {
				continue
			}
			if err != nil {
				return err
			}
			if channelEnabled == 0 {
				continue
			}
			if _, err := tx.ExecContext(ctx, `INSERT INTO alert_notifications
				(id, event_id, channel_id, channel_type, status, attempts, last_error, next_attempt_at, sent_at, created_at, updated_at)
				VALUES (?, ?, ?, ?, 'pending', 0, '', ?, '', ?, ?)`,
				uuid.NewString(), event.ID, channelID, channelType, formatAlertTime(now), formatAlertTime(now), formatAlertTime(now)); err != nil {
				return err
			}
			inserted++
		}
		if inserted == 0 && event.Status == AlertStatusFiring {
			if _, err := tx.ExecContext(ctx, `UPDATE alert_events SET notified = 0 WHERE id = ?`, event.ID); err != nil {
				return err
			}
		}
	}
	return tx.Commit()
}

