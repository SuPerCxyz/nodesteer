func (r *AlertRepository) CreateAlertRule(ctx context.Context, rule *AlertRule) error {
	if rule.ID != "" {
		return fmt.Errorf("%w: rule id must be generated by the server", ErrInvalidAlertRule)
	}
	rule.Normalize()
	if err := rule.Validate(); err != nil {
		return err
	}
	now := time.Now().UTC()
	rule.ID = uuid.NewString()
	rule.CreatedAt = now
	rule.UpdatedAt = now
	channels, err := json.Marshal(rule.Channels)
	if err != nil {
		return err
	}
	silence := ""
	if rule.SilenceUntil != nil {
		silence = formatAlertTime(*rule.SilenceUntil)
	}
	tx, err := r.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if _, err := tx.ExecContext(ctx, `INSERT INTO alert_rules
		(id, name, description, node_id, metric, series, operator, threshold,
		 duration_sec, recovery_sec, cooldown_sec, severity, channels_json, enabled,
		 silence_until, created_at, updated_at)
		VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
		rule.ID, rule.Name, rule.Description, rule.NodeID, rule.Metric, rule.Series,
		rule.Operator, rule.Threshold, rule.DurationSec, rule.RecoverySec, rule.CooldownSec,
		rule.Severity, string(channels), boolInt(rule.Enabled), silence,
		formatAlertTime(rule.CreatedAt), formatAlertTime(rule.UpdatedAt)); err != nil {
		return err
	}
	if err := writeAudit(ctx, tx, "alert_rule", "create", rule.ID); err != nil {
		return err
	}
	return tx.Commit()
}

