func (r *AlertRepository) UpdateAlertRule(ctx context.Context, rule AlertRule) error {
	if rule.ID == "" {
		return fmt.Errorf("%w: rule id required", ErrInvalidAlertRule)
	}
	rule.Normalize()
	if err := rule.Validate(); err != nil {
		return err
	}
	now := time.Now().UTC()
	rule.UpdatedAt = now
	channels, err := json.Marshal(rule.Channels)
	if err != nil {
		return err
	}
	tx, err := r.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	old, err := getAlertRuleTx(ctx, tx, rule.ID)
	if err != nil {
		return err
	}
	// PUT 未携带 silenced_until 时保留现有静默；显式解除走 DELETE /silence。
	if rule.SilenceUntil == nil && old.SilenceUntil != nil {
		rule.SilenceUntil = old.SilenceUntil
	}
	silence := ""
	if rule.SilenceUntil != nil {
		silence = formatAlertTime(*rule.SilenceUntil)
	}
	result, err := tx.ExecContext(ctx, `UPDATE alert_rules SET
		name = ?, description = ?, node_id = ?, metric = ?, series = ?, operator = ?,
		threshold = ?, duration_sec = ?, recovery_sec = ?, cooldown_sec = ?, severity = ?,
		channels_json = ?, enabled = ?, silence_until = ?, updated_at = ?
		WHERE id = ?`,
		rule.Name, rule.Description, rule.NodeID, rule.Metric, rule.Series, rule.Operator,
		rule.Threshold, rule.DurationSec, rule.RecoverySec, rule.CooldownSec, rule.Severity,
		string(channels), boolInt(rule.Enabled), silence, formatAlertTime(rule.UpdatedAt), rule.ID)
	if err != nil {
		return err
	}
	affected, err := result.RowsAffected()
	if err != nil {
		return err
	}
	if affected == 0 {
		return sql.ErrNoRows
	}
	switch {
	case old.Enabled && !rule.Enabled:
		if err := resetAlertRuntimeTx(ctx, tx, rule.ID, "rule disabled", now); err != nil {
			return err
		}
	case !old.Enabled && rule.Enabled:
		if _, err := tx.ExecContext(ctx, `DELETE FROM alert_states WHERE rule_id = ?`, rule.ID); err != nil {
			return err
		}
	case ruleRuntimeChanged(old, rule):
		if err := resetAlertRuntimeTx(ctx, tx, rule.ID, "rule updated", now); err != nil {
			return err
		}
	default:
		if _, err := tx.ExecContext(ctx, `UPDATE alert_events SET rule_name = ?, severity = ?, updated_at = ?
			WHERE rule_id = ? AND status IN ('pending', 'firing', 'silenced')`,
			rule.Name, rule.Severity, formatAlertTime(now), rule.ID); err != nil {
			return err
		}
	}
	if err := writeAudit(ctx, tx, "alert_rule", "update", rule.ID); err != nil {
		return err
	}
	return tx.Commit()
}

func (r *AlertRepository) DeleteAlertRule(ctx context.Context, id string) error {
	tx, err := r.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if _, err := getAlertRuleTx(ctx, tx, id); err != nil {
		return err
	}
	now := time.Now().UTC()
	if err := resetAlertRuntimeTx(ctx, tx, id, "rule deleted", now); err != nil {
		return err
	}
	result, err := tx.ExecContext(ctx, `DELETE FROM alert_rules WHERE id = ?`, id)
	if err != nil {
		return err
	}
	affected, err := result.RowsAffected()
	if err != nil {
		return err
	}
	if affected == 0 {
		return sql.ErrNoRows
	}
	if err := writeAudit(ctx, tx, "alert_rule", "delete", id); err != nil {
		return err
	}
	return tx.Commit()
}

func (r *AlertRepository) SetAlertRuleEnabled(ctx context.Context, id string, enabled bool) error {
	tx, err := r.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	rule, err := getAlertRuleTx(ctx, tx, id)
	if err != nil {
		return err
	}
	if rule.Enabled == enabled {
		return tx.Commit()
	}
	now := time.Now().UTC()
	if _, err := tx.ExecContext(ctx, `UPDATE alert_rules SET enabled = ?, updated_at = ? WHERE id = ?`,
		boolInt(enabled), formatAlertTime(now), id); err != nil {
		return err
	}
	if enabled {
		if _, err := tx.ExecContext(ctx, `DELETE FROM alert_states WHERE rule_id = ?`, id); err != nil {
			return err
		}
	} else if err := resetAlertRuntimeTx(ctx, tx, id, "rule disabled", now); err != nil {
		return err
	}
	action := "disable"
	if enabled {
		action = "enable"
	}
	if err := writeAudit(ctx, tx, "alert_rule", action, id); err != nil {
		return err
	}
	return tx.Commit()
}

func (r *AlertRepository) SetAlertRuleSilence(ctx context.Context, id string, until time.Time) error {
	until = until.UTC()
	if !until.After(time.Now().UTC()) {
		return fmt.Errorf("%w: silence time must be in the future", ErrInvalidAlertRule)
	}
	tx, err := r.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if _, err := getAlertRuleTx(ctx, tx, id); err != nil {
		return err
	}
	now := time.Now().UTC()
	stamp := formatAlertTime(until)
	if _, err := tx.ExecContext(ctx, `UPDATE alert_rules SET silence_until = ?, updated_at = ? WHERE id = ?`,
		stamp, formatAlertTime(now), id); err != nil {
		return err
	}
	// 静默立即生效：取消尚未发送的旧通知。
	if _, err := tx.ExecContext(ctx, `UPDATE alert_notifications SET status = 'failed', last_error = 'rule silenced', next_attempt_at = '', updated_at = ?
		WHERE status = 'pending' AND event_id IN (SELECT id FROM alert_events WHERE rule_id = ?)`,
		formatAlertTime(now), id); err != nil {
		return err
	}
	if _, err := tx.ExecContext(ctx, `UPDATE alert_events SET status = 'silenced', silenced_until = ?, updated_at = ?
		WHERE rule_id = ? AND status = 'firing'`, stamp, formatAlertTime(now), id); err != nil {
		return err
	}
	if _, err := tx.ExecContext(ctx, `UPDATE alert_states SET status = 'silenced', message = ?, updated_at = ?
		WHERE rule_id = ? AND status = 'firing'`, "silenced until "+stamp, formatAlertTime(now), id); err != nil {
		return err
	}
	if err := writeAuditDetail(ctx, tx, "alert_rule", "silence", id, "until="+stamp); err != nil {
		return err
	}
	return tx.Commit()
}

func (r *AlertRepository) ClearAlertRuleSilence(ctx context.Context, id string) error {
	tx, err := r.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if _, err := getAlertRuleTx(ctx, tx, id); err != nil {
		return err
	}
	now := time.Now().UTC()
	if _, err := tx.ExecContext(ctx, `UPDATE alert_rules SET silence_until = '', updated_at = ? WHERE id = ?`,
		formatAlertTime(now), id); err != nil {
		return err
	}
	if _, err := tx.ExecContext(ctx, `UPDATE alert_events SET status = 'firing', silenced_until = '', updated_at = ?
		WHERE rule_id = ? AND status = 'silenced'`, formatAlertTime(now), id); err != nil {
		return err
	}
	if _, err := tx.ExecContext(ctx, `UPDATE alert_states SET status = 'firing', message = '', updated_at = ?
		WHERE rule_id = ? AND status = 'silenced'`, formatAlertTime(now), id); err != nil {
		return err
	}
	if err := writeAudit(ctx, tx, "alert_rule", "unsilence", id); err != nil {
		return err
	}
	return tx.Commit()
}

func (r *AlertRepository) ChannelIDsExist(ctx context.Context, ids []string) error {
	if len(ids) == 0 {
		return nil
	}
	seen := map[string]bool{}
	unique := make([]string, 0, len(ids))
	for _, id := range ids {
		if id == "" || seen[id] {
			continue
		}
		seen[id] = true
		unique = append(unique, id)
	}
	if len(unique) == 0 {
		return nil
	}
	placeholders := strings.TrimRight(strings.Repeat("?,", len(unique)), ",")
	args := make([]any, 0, len(unique))
	for _, id := range unique {
		args = append(args, id)
	}
	var count int
	if err := r.db.QueryRowContext(ctx, `SELECT COUNT(*) FROM notification_channels WHERE id IN (`+placeholders+`)`, args...).Scan(&count); err != nil {
		return err
	}
	if count != len(unique) {
		return ErrAlertChannelNotFound
	}
	return nil
}

