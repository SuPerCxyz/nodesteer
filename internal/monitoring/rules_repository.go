// ResolveUnknown requires an administrator to inspect an unresolved outcome,
// whether uncertain (unknown) or definitively failed. fired remains set so
// resolving an event cannot immediately run the task again.
func (r *Repository) ResolveUnknown(ctx context.Context, ruleID string) error {
	tx, err := r.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	var pending string
	if err := tx.QueryRowContext(ctx, `SELECT pending_id FROM monitoring_rules WHERE id = ?`, ruleID).Scan(&pending); err != nil {
		return err
	}
	if pending == "" {
		return errors.New("rule has no unresolved execution")
	}
	nonterminal, err := store.CountNonTerminalMonitoringExecutionsTx(ctx, tx, pending)
	if err != nil {
		return err
	}
	if nonterminal > 0 {
		return errors.New("monitoring executions are still active or unknown")
	}
	var previousStatus string
	if err := tx.QueryRowContext(ctx, `SELECT status FROM monitoring_rule_events WHERE id = ? AND rule_id = ?`, pending, ruleID).Scan(&previousStatus); errors.Is(err, sql.ErrNoRows) {
		return errors.New("execution is still in progress")
	} else if err != nil {
		return err
	}
	result, err := tx.ExecContext(ctx, `UPDATE monitoring_rule_events SET status = CASE status WHEN 'unknown' THEN 'acknowledged_unknown' WHEN 'failed' THEN 'acknowledged_failed' END WHERE id = ? AND rule_id = ? AND status IN ('unknown', 'failed')`, pending, ruleID)
	if err != nil {
		return err
	}
	count, err := result.RowsAffected()
	if err != nil {
		return err
	}
	if count != 1 {
		return errors.New("execution is still in progress")
	}
	if _, err := tx.ExecContext(ctx, `UPDATE monitoring_rules SET pending_id = '' WHERE id = ? AND pending_id = ?`, ruleID, pending); err != nil {
		return err
	}
	if err := writeAuditDetail(ctx, tx, "monitoring_rule", "resolve_unknown", ruleID, fmt.Sprintf("event_id=%s; previous_status=%s", pending, previousStatus)); err != nil {
		return err
	}
	return tx.Commit()
}

// AbandonUnknown is an explicit administrator action for an unknown event
// whose executions may never report again. It records linked non-terminal
// executions as BLOCKED and closes the event without cancelling node-side work.
func (r *Repository) AbandonUnknown(ctx context.Context, ruleID string) error {
	tx, err := r.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	var pending string
	if err := tx.QueryRowContext(ctx, `SELECT pending_id FROM monitoring_rules WHERE id = ?`, ruleID).Scan(&pending); err != nil {
		return err
	}
	if pending == "" {
		return errors.New("rule has no unresolved execution")
	}
	var status, originalError string
	err = tx.QueryRowContext(ctx, `SELECT status, error FROM monitoring_rule_events WHERE id = ? AND rule_id = ?`, pending, ruleID).Scan(&status, &originalError)
	if errors.Is(err, sql.ErrNoRows) {
		return errors.New("monitoring event is not unknown")
	}
	if err != nil {
		return err
	}
	if status != "unknown" {
		return errors.New("monitoring event is not unknown")
	}
	nonterminal, err := store.CountNonTerminalMonitoringExecutionsTx(ctx, tx, pending)
	if err != nil {
		return err
	}
	if nonterminal == 0 {
		return errors.New("monitoring executions are already terminal; use ResolveUnknown")
	}
	blocked, err := store.AbandonMonitoringExecutionsTx(ctx, tx, pending, AbandonReason)
	if err != nil {
		return err
	}
	eventError := AbandonReason
	if strings.TrimSpace(originalError) != "" {
		eventError = originalError + "; " + AbandonReason
	}
	eventError = sanitizeEventMessage(eventError)
	result, err := tx.ExecContext(ctx, `UPDATE monitoring_rule_events SET status = 'abandoned_unknown', error = ? WHERE id = ? AND rule_id = ? AND status = 'unknown'`, eventError, pending, ruleID)
	if err != nil {
		return err
	}
	affected, err := result.RowsAffected()
	if err != nil {
		return err
	}
	if affected != 1 {
		return errors.New("monitoring event is not unknown")
	}
	result, err = tx.ExecContext(ctx, `UPDATE monitoring_rules SET pending_id = '' WHERE id = ? AND pending_id = ?`, ruleID, pending)
	if err != nil {
		return err
	}
	affected, err = result.RowsAffected()
	if err != nil {
		return err
	}
	if affected != 1 {
		return errors.New("rule has no unresolved execution")
	}
	detail := fmt.Sprintf("event_id=%s; blocked_executions=%d; error=%s", pending, blocked, auditErrorSummary(originalError))
	if err := writeAuditDetail(ctx, tx, "monitoring_rule", "abandon_unknown", ruleID, detail); err != nil {
		return err
	}
	return tx.Commit()
}

func sanitizeEventMessage(message string) string {
	message = strings.Map(func(r rune) rune {
		if r == '\n' || r == '\t' {
			return ' '
		}
		if r < 0x20 || r == 0x7f {
			return -1
		}
		return r
	}, message)
	runes := []rune(strings.TrimSpace(message))
	if len(runes) > 512 {
		message = string(runes[:512]) + "..."
	} else {
		message = string(runes)
	}
	return message
}

func auditErrorSummary(message string) string {
	message = strings.TrimSpace(message)
	if message == "" {
		return "none"
	}
	lower := strings.ToLower(message)
	for _, marker := range []string{
		"sql:", "sqlite", "database is locked", "database table is locked",
		"constraint failed", "no such table", "no such column",
		"disk image is malformed", "readonly database", "disk i/o error",
	} {
		if strings.Contains(lower, marker) {
			return "storage error"
		}
	}
	runes := []rune(message)
	if len(runes) > 200 {
		message = string(runes[:200]) + "..."
	}
	return message
}

func mustMarshalRule(rule Rule) []byte { data, _ := json.Marshal(rule); return data }

// Fixed-width UTC timestamps preserve chronological order in SQLite text comparisons.
func sampleWindowTimestamp(t time.Time) string {
	return t.UTC().Format("2006-01-02T15:04:05.000000000Z")
}
