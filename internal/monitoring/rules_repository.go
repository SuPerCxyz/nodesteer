type Rule struct {
	ID                   string `json:"id"`
	Name                 string `json:"name"`
	TargetID             string `json:"target_id"`
	ScheduleID           string `json:"schedule_id"`
	Operator             string `json:"operator"`
	Expected             string `json:"expected"`
	DurationSec          int    `json:"duration_sec"`
	CooldownSec          int    `json:"cooldown_sec"`
	BatchSize            int    `json:"batch_size,omitempty"`
	VerifyScheduleID     string `json:"verify_schedule_id,omitempty"`
	CompensateScheduleID string `json:"compensate_schedule_id,omitempty"`
	Enabled              bool   `json:"enabled"`
}

var ErrCompensated = errors.New("monitoring action failed and was compensated")

// ErrKnownFailure marks a monitoring action failure whose outcome is definitive:
// the action either never started or every result is already known. Unlike an
// unknown outcome, no remote side effect can have escaped observation, so the
// event can be recorded as failed instead of fail-closed unknown.
var ErrKnownFailure = errors.New("monitoring action failed with a known outcome")

func (rule Rule) Validate() error {
	if rule.Name == "" || len(rule.Name) > 128 || rule.TargetID == "" || rule.ScheduleID == "" || rule.DurationSec < 0 || rule.DurationSec > 86400 || rule.CooldownSec < 0 || rule.CooldownSec > 604800 || rule.BatchSize < 0 || rule.BatchSize > 20 || len(rule.Expected) > 256 {
		return errors.New("invalid monitoring rule")
	}
	if rule.VerifyScheduleID != "" && rule.VerifyScheduleID == rule.ScheduleID {
		return errors.New("verify schedule must differ from action schedule")
	}
	if rule.CompensateScheduleID != "" && (rule.CompensateScheduleID == rule.ScheduleID || rule.CompensateScheduleID == rule.VerifyScheduleID) {
		return errors.New("compensate schedule must differ from action and verify schedules")
	}
	switch rule.Operator {
	case "status_eq":
		value, err := strconv.Atoi(rule.Expected)
		if err != nil || value < 100 || value > 599 {
			return errors.New("invalid HTTP status")
		}
	case "lt", "gt":
		value, err := strconv.ParseFloat(rule.Expected, 64)
		if err != nil || math.IsNaN(value) || math.IsInf(value, 0) || math.Abs(value) >= 1<<53 {
			return errors.New("invalid numeric threshold")
		}
	case "expires_within":
		value, err := time.ParseDuration(rule.Expected)
		if err != nil || value < 0 {
			return errors.New("invalid expiry threshold")
		}
	case "eq":
	case "probe_error":
	default:
		return errors.New("unsupported monitoring rule operator")
	}
	return nil
}

func ValidateRuleTarget(rule Rule, target Target) error {
	switch target.Kind {
	case "node_metric":
		if rule.Operator != "eq" && rule.Operator != "lt" && rule.Operator != "gt" {
			return errors.New("node metric requires a numeric comparison")
		}
		value, err := strconv.ParseFloat(rule.Expected, 64)
		if err != nil || math.IsNaN(value) || math.IsInf(value, 0) || math.Abs(value) >= 1<<53 {
			return errors.New("invalid numeric threshold")
		}
	case "tcp", "icmp":
		if rule.Operator != "probe_error" {
			return errors.New("network target only supports probe_error")
		}
	default:
		// HTTP targets can compare status without a value, but any business
		// value comparison needs an explicit JSON path.
		if rule.Operator != "status_eq" && rule.Operator != "probe_error" && len(target.JSONPath) == 0 {
			return errors.New("HTTP value comparison requires a JSON path")
		}
	}
	return nil
}

func (r *Repository) CreateRule(ctx context.Context, rule *Rule) error {
	if rule.ID != "" {
		return errors.New("rule id must be generated by the server")
	}
	if err := rule.Validate(); err != nil {
		return err
	}
	target, err := r.Get(ctx, rule.TargetID)
	if err != nil {
		return err
	}
	if err := ValidateRuleTarget(*rule, target); err != nil {
		return err
	}
	rule.ID = uuid.NewString()
	data, err := json.Marshal(rule)
	if err != nil {
		return err
	}
	tx, err := r.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if _, err := tx.ExecContext(ctx, `INSERT INTO monitoring_rules (id, target_id, config_json, not_before) VALUES (?, ?, ?, ?)`, rule.ID, rule.TargetID, string(data), time.Now().UTC().Format(time.RFC3339Nano)); err != nil {
		return err
	}
	if err := writeAudit(ctx, tx, "monitoring_rule", "create", rule.ID); err != nil {
		return err
	}
	return tx.Commit()
}

func (r *Repository) Rules(ctx context.Context, targetID string) ([]Rule, error) {
	query := `SELECT config_json FROM monitoring_rules`
	args := []any{}
	if targetID != "" {
		query += ` WHERE target_id = ?`
		args = append(args, targetID)
	}
	query += ` ORDER BY id`
	rows, err := r.db.QueryContext(ctx, query, args...)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []Rule{}
	for rows.Next() {
		var raw string
		var rule Rule
		if err := rows.Scan(&raw); err != nil {
			return nil, err
		}
		if err := json.Unmarshal([]byte(raw), &rule); err != nil {
			return nil, err
		}
		out = append(out, rule)
	}
	return out, rows.Err()
}

func (r *Repository) GetRule(ctx context.Context, id string) (Rule, error) {
	var raw string
	var rule Rule
	if err := r.db.QueryRowContext(ctx, `SELECT config_json FROM monitoring_rules WHERE id = ?`, id).Scan(&raw); err != nil {
		return rule, err
	}
	if err := json.Unmarshal([]byte(raw), &rule); err != nil {
		return rule, err
	}
	return rule, nil
}

func (r *Repository) UpdateRule(ctx context.Context, rule Rule) error {
	if rule.ID == "" {
		return errors.New("rule id required")
	}
	if err := rule.Validate(); err != nil {
		return err
	}
	data, err := json.Marshal(rule)
	if err != nil {
		return err
	}
	tx, err := r.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	var pending, oldConfig string
	if err := tx.QueryRowContext(ctx, `SELECT pending_id, config_json FROM monitoring_rules WHERE id = ?`, rule.ID).Scan(&pending, &oldConfig); err != nil {
		return err
	}
	if pending != "" {
		var old Rule
		if err := json.Unmarshal([]byte(oldConfig), &old); err != nil {
			return err
		}
		candidate := rule
		candidate.Enabled = old.Enabled
		if rule.Enabled || candidate != old {
			return errors.New("only disabling is allowed while rule execution is pending")
		}
		if _, err := tx.ExecContext(ctx, `UPDATE monitoring_rules SET config_json = ?, interrupted = 1, last_confirmed_at = '' WHERE id = ?`, string(data), rule.ID); err != nil {
			return err
		}
		if err := writeAudit(ctx, tx, "monitoring_rule", "disable", rule.ID); err != nil {
			return err
		}
		return tx.Commit()
	}
	var targetConfig string
	if err := tx.QueryRowContext(ctx, `SELECT config_json FROM monitoring_http_targets WHERE id = ?`, rule.TargetID).Scan(&targetConfig); err != nil {
		return err
	}
	var target Target
	if err := json.Unmarshal([]byte(targetConfig), &target); err != nil {
		return err
	}
	if err := ValidateRuleTarget(rule, target); err != nil {
		return err
	}
	if _, err := tx.ExecContext(ctx, `UPDATE monitoring_rules SET target_id = ?, config_json = ?, active_since = '', last_observed = '', last_sample = '', not_before = ? WHERE id = ?`, rule.TargetID, string(data), time.Now().UTC().Format(time.RFC3339Nano), rule.ID); err != nil {
		return err
	}
	if _, err := tx.ExecContext(ctx, `DELETE FROM monitoring_rule_samples WHERE rule_id=?`, rule.ID); err != nil {
		return err
	}
	if err := writeAudit(ctx, tx, "monitoring_rule", "update", rule.ID); err != nil {
		return err
	}
	return tx.Commit()
}

func (r *Repository) DeleteRule(ctx context.Context, id string) error {
	tx, err := r.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	result, err := tx.ExecContext(ctx, `DELETE FROM monitoring_rules WHERE id = ? AND pending_id = ''`, id)
	if err != nil {
		return err
	}
	count, err := result.RowsAffected()
	if err != nil {
		return err
	}
	if count == 0 {
		return sql.ErrNoRows
	}
	if err := writeAudit(ctx, tx, "monitoring_rule", "delete", id); err != nil {
		return err
	}
	return tx.Commit()
}

// ClaimRule atomically records the incident before any remote action. now is
// the observation's source timestamp, not the wall clock at query time.
func (r *Repository) ClaimRule(ctx context.Context, rule Rule, target Target, matched bool, now time.Time, maxGap time.Duration, observations ...HTTPObservation) (string, error) {
	return r.claimRule(ctx, rule, target, matched, now, maxGap, true, observations...)
}

func (r *Repository) claimRule(ctx context.Context, rule Rule, target Target, matched bool, now time.Time, maxGap time.Duration, allowTrigger bool, observations ...HTTPObservation) (string, error) {
	if err := ValidateRuleTarget(rule, target); err != nil {
		return "", err
	}
	tx, err := r.db.BeginTx(ctx, nil)
	if err != nil {
		return "", err
	}
	defer tx.Rollback()
	claim, err := r.claimRuleTx(ctx, tx, rule, target, matched, now, maxGap, allowTrigger, observations...)
	if err != nil {
		return "", err
	}
	if err := tx.Commit(); err != nil {
		return "", err
	}
	return claim, nil
}

func (r *Repository) claimRuleTx(ctx context.Context, tx *sql.Tx, rule Rule, target Target, matched bool, now time.Time, maxGap time.Duration, allowTrigger bool, observations ...HTTPObservation) (string, error) {
	var targetConfig string
	if err := tx.QueryRowContext(ctx, `SELECT config_json FROM monitoring_http_targets WHERE id = ?`, rule.TargetID).Scan(&targetConfig); err != nil {
		return "", err
	}
	expectedTarget, _ := json.Marshal(target)
	if targetConfig != string(expectedTarget) {
		return "", nil
	}
	if target.Kind == "node_metric" {
		var online int
		if err := tx.QueryRowContext(ctx, `SELECT COUNT(*) FROM nodes WHERE id = ? AND status = ?`, target.MonitoredNodeID, models.NodeStatusOnline).Scan(&online); err != nil {
			return "", err
		}
		if online != 1 {
			if _, err := tx.ExecContext(ctx, `UPDATE monitoring_rules SET active_since='', last_observed='', last_confirmed_at='', interrupted=CASE WHEN pending_id <> '' THEN 1 ELSE interrupted END WHERE id=?`, rule.ID); err != nil {
				return "", err
			}
			return "", nil
		}
	}
	var config, active, last, pending, observed, notBefore, lastSample string
	var fired, interrupted int
	if err := tx.QueryRowContext(ctx, `SELECT config_json, active_since, last_trigger, pending_id, fired, last_observed, interrupted, not_before, last_sample FROM monitoring_rules WHERE id = ?`, rule.ID).Scan(&config, &active, &last, &pending, &fired, &observed, &interrupted, &notBefore, &lastSample); err != nil {
		return "", err
	}
	expected, _ := json.Marshal(rule)
	if config != string(expected) || !rule.Enabled {
		return "", nil
	}
	if pending != "" && interrupted != 0 {
		return "", nil
	}
	previous, _ := time.Parse(time.RFC3339Nano, observed)
	if target.Kind == "node_metric" {
		boundary, _ := time.Parse(time.RFC3339Nano, notBefore)
		if !boundary.IsZero() && !now.After(boundary) || !previous.IsZero() && now.Before(previous) {
			return "", nil
		}
		if !previous.IsZero() && now.Equal(previous) {
			if len(observations) == 0 || !observations[0].HasValue {
				return "", nil
			}
			encoded, err := json.Marshal(observations[0].Value)
			if err != nil {
				return "", err
			}
			if lastSample == "" {
				return "", nil
			} // pre-migration cursor: wait for a newer sample
			if lastSample != "v:"+string(encoded) {
				_, err := tx.ExecContext(ctx, `UPDATE monitoring_rules SET active_since='', last_confirmed_at='', not_before=?, interrupted=CASE WHEN pending_id<>'' THEN 1 ELSE interrupted END WHERE id=?`, time.Now().UTC().Format(time.RFC3339Nano), rule.ID)
				return "", err
			}
			// The source can discover a gap without advancing the newest point.
			// Check continuity before the duplicate-point fast path.
			if !observations[0].ContinuityStart.IsZero() {
				started, _ := time.Parse(time.RFC3339Nano, active)
				if !started.IsZero() && started.Before(observations[0].ContinuityStart) {
					_, err := tx.ExecContext(ctx, `UPDATE monitoring_rules SET active_since='', last_confirmed_at='', interrupted=CASE WHEN pending_id<>'' THEN 1 ELSE interrupted END WHERE id=?`, rule.ID)
					return "", err
				}
			}
			// An identical, still-fresh final point can acquire a newly available slot.
			if !allowTrigger || pending != "" || fired != 0 || !matched || active == "" {
				return "", nil
			}
		}
	}
	brokenContinuity := false
	if !previous.IsZero() && (now.Before(previous) || now.Sub(previous) > maxGap) {
		active = ""
		brokenContinuity = true
	}
	if len(observations) > 0 && !observations[0].ContinuityStart.IsZero() {
		activeTime, _ := time.Parse(time.RFC3339Nano, active)
		if !activeTime.IsZero() && activeTime.Before(observations[0].ContinuityStart) {
			active = ""
			brokenContinuity = true
		}
	}
	if pending != "" && (!matched || brokenContinuity) {
		if _, err := tx.ExecContext(ctx, `UPDATE monitoring_rules SET active_since='', last_observed='', last_confirmed_at='', interrupted=1 WHERE id=?`, rule.ID); err != nil {
			return "", err
		}
		return "", nil
	}
	sampleIdentity := ""
	if target.Kind == "node_metric" && len(observations) > 0 && observations[0].HasValue {
		encoded, err := json.Marshal(observations[0].Value)
		if err != nil {
			return "", err
		}
		sampleIdentity = "v:" + string(encoded)
	}
	if _, err := tx.ExecContext(ctx, `UPDATE monitoring_rules SET last_observed = ?, last_sample = ? WHERE id = ?`, now.UTC().Format(time.RFC3339Nano), sampleIdentity, rule.ID); err != nil {
		return "", err
	}
	if !matched {
		_, err := tx.ExecContext(ctx, `UPDATE monitoring_rules SET active_since = '', last_confirmed_at = '', fired = CASE WHEN pending_id = '' THEN 0 ELSE fired END WHERE id = ?`, rule.ID)
		if err != nil {
			return "", err
		}
		return "", nil
	}
	if active == "" {
		active = now.UTC().Format(time.RFC3339Nano)
		if _, err := tx.ExecContext(ctx, `UPDATE monitoring_rules SET active_since = ? WHERE id = ?`, active, rule.ID); err != nil {
			return "", err
		}
	}
	start, err := time.Parse(time.RFC3339Nano, active)
	if err != nil {
		return "", err
	}
	if pending != "" {
		confirmed := ""
		if now.Sub(start) >= time.Duration(rule.DurationSec)*time.Second {
			confirmed = now.UTC().Format(time.RFC3339Nano)
		}
		if _, err := tx.ExecContext(ctx, `UPDATE monitoring_rules SET last_confirmed_at = ? WHERE id = ?`, confirmed, rule.ID); err != nil {
			return "", err
		}
		return "", nil
	}
	if !allowTrigger {
		return "", nil
	}
	lastTime, _ := time.Parse(time.RFC3339Nano, last)
	if fired != 0 || now.Sub(start) < time.Duration(rule.DurationSec)*time.Second || (!lastTime.IsZero() && now.Sub(lastTime) < time.Duration(rule.CooldownSec)*time.Second) {
		return "", nil
	}
	claim := uuid.NewString()
	observationJSON := []byte("{}")
	if len(observations) > 0 {
		var err error
		observationJSON, err = json.Marshal(struct {
			StatusCode int  `json:"status_code"`
			Value      any  `json:"value"`
			HasValue   bool `json:"has_value"`
		}{observations[0].StatusCode, observations[0].Value, observations[0].HasValue})
		if err != nil {
			return "", err
		}
	}
	if _, err := tx.ExecContext(ctx, `INSERT INTO monitoring_rule_events (id, rule_id, target_id, observed_at, status, observation_json, rule_snapshot) VALUES (?, ?, ?, ?, 'pending', ?, ?)`, claim, rule.ID, rule.TargetID, now.UTC().Format(time.RFC3339Nano), string(observationJSON), config); err != nil {
		return "", err
	}
	if _, err := tx.ExecContext(ctx, `UPDATE monitoring_rules SET pending_id = ?, fired = 1, last_trigger = ?, last_confirmed_at = ?, interrupted = 0 WHERE id = ?`, claim, now.UTC().Format(time.RFC3339Nano), now.UTC().Format(time.RFC3339Nano), rule.ID); err != nil {
		return "", err
	}
	return claim, nil
}

